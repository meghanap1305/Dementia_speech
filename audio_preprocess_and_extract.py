"""## Cell 2 — Preprocessing
Converts raw `.mp3` → clean 16 kHz mono `.wav`  
Internal pauses are **preserved** (they are a primary AD biomarker).  
Only leading/trailing edge silence is removed.
"""

import warnings, logging
warnings.filterwarnings('ignore')
logging.basicConfig(level=logging.INFO, format='%(asctime)s | %(levelname)-8s | %(message)s', datefmt='%H:%M:%S')
log = logging.getLogger(__name__)

from pathlib import Path
import numpy as np
import pandas as pd
import librosa
import soundfile as sf
import noisereduce as nr
from pydub import AudioSegment
from sklearn.model_selection import train_test_split
from tqdm.notebook import tqdm

# ── Paths ─────────────────────────────────────────────────────────────────────
INPUT_DIR    = Path('/content/drive/MyDrive/pitt_corpus/audio')
OUTPUT_DIR   = Path('/content/processed_audio')   # Colab local disk (faster I/O)
MANIFEST_OUT = Path('/content/audio_manifest.csv')

# ── Config ────────────────────────────────────────────────────────────────────
SAMPLE_RATE      = 16_000   # Hz — hard requirement for Wav2Vec 2.0
TEST_SIZE        = 0.20     # 80/20 stratified split
RANDOM_STATE     = 42
EDGE_TRIM_TOP_DB = 30       # dB threshold for edge silence detection only
NOISE_PROFILE_S  = 0.5      # seconds used as noise profile for spectral subtraction
MIN_DURATION_S   = 2.0      # discard files shorter than this after trimming
LABEL_MAP        = {'Dementia': 1, 'Control': 0}

# ── Step 1: Discover files ────────────────────────────────────────────────────
def discover_files(input_dir):
    records = []
    for label_str in LABEL_MAP:
        folder = input_dir / label_str
        if not folder.exists():
            log.warning('Folder not found: %s', folder)
            continue
        for mp3 in sorted(folder.glob('*.mp3')):
            records.append({
                'subject_id': mp3.stem,
                'raw_path':   str(mp3),
                'label_str':  label_str,
                'label':      LABEL_MAP[label_str],
            })
    df = pd.DataFrame(records)
    # Modified line: Check if 'label' column exists before summing
    if 'label' in df.columns:
        log.info('Found %d files  (Dementia=%d  Control=%d)',
                 len(df), (df.label==1).sum(), (df.label==0).sum())
    else:
        # If no files found, df is empty and 'label' column doesn't exist
        log.info('Found %d files. No MP3 files found in specified directories.', len(df))
    return df

# ── Step 2: Stratified split ──────────────────────────────────────────────────
def stratified_split(df):
    # Added check for empty DataFrame before splitting
    if df.empty:
        log.info('DataFrame is empty, skipping stratified split.')
        # Return a DataFrame with 'split' column to avoid downstream errors, even if empty
        return pd.DataFrame(columns=df.columns.tolist() + ['split'])

    _, test_df = train_test_split(
        df, test_size=TEST_SIZE,
        stratify=df['label'],
        random_state=RANDOM_STATE,
    )
    df = df.copy()
    df['split'] = 'train'
    df.loc[test_df.index, 'split'] = 'test'
    log.info('Split → train=%d  test=%d',
             (df.split=='train').sum(), (df.split=='test').sum())
    return df

# ── Step 3: Decode MP3 ────────────────────────────────────────────────────────
def decode_mp3(path):
    audio = AudioSegment.from_mp3(path)
    audio = audio.set_channels(1).set_frame_rate(SAMPLE_RATE)
    samples = np.array(audio.get_array_of_samples(), dtype=np.float32)
    samples /= np.iinfo(audio.array_type).max
    return samples

# ── Step 4: Background noise reduction ───────────────────────────────────────
def reduce_noise(y):
    """
    Spectral subtraction using the first 0.5 s as noise profile.
    prop_decrease=0.75 is conservative — avoids over-suppressing speech.
    All speech content including pauses is preserved.
    """
    noise_len  = int(NOISE_PROFILE_S * SAMPLE_RATE)
    noise_clip = y[:noise_len] if len(y) > noise_len else y
    y_clean = nr.reduce_noise(
        y=y, sr=SAMPLE_RATE,
        y_noise=noise_clip,
        stationary=False,
        prop_decrease=0.75,
    )
    return y_clean.astype(np.float32)

# ── Step 5: Edge-only silence trim ────────────────────────────────────────────
def trim_edges_only(y):
    """
    Removes silence ONLY at the very start and end of the file.
    Mid-speech pauses are NOT touched — they are critical AD biomarkers:
      - AD patients pause more frequently
      - Longer pauses indicate word-finding difficulty
      - Pause-to-speech ratio correlates with MMSE score
    librosa.effects.trim() returns (trimmed_audio, (start_sample, end_sample))
    We use the indices to slice the original array — nothing inside is changed.
    """
    _, (start, end) = librosa.effects.trim(y, top_db=EDGE_TRIM_TOP_DB)
    return y[start:end]

# ── Step 6: Peak normalisation ────────────────────────────────────────────────
def peak_normalise(y):
    peak = np.max(np.abs(y))
    return (y / peak * 0.99).astype(np.float32) if peak > 0 else y

# ── Step 7: Process one file ──────────────────────────────────────────────────
def process_one(row, stats):
    out_dir  = OUTPUT_DIR / row['split'] / row['label_str']
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / (row['subject_id'] + '.wav')

    try:
        y = decode_mp3(row['raw_path'])
        y = reduce_noise(y)
        y = trim_edges_only(y)          # internal pauses preserved

        duration_s = len(y) / SAMPLE_RATE
        if duration_s < MIN_DURATION_S:
            log.warning('Skip %s — too short (%.2fs)', row['subject_id'], duration_s)
            stats['skipped'] += 1
            return {'wav_path': '', 'duration_s': round(duration_s,3), 'status': 'skipped'}

        y = peak_normalise(y)
        sf.write(str(out_path), y, SAMPLE_RATE, subtype='PCM_16')
        stats['ok'] += 1
        return {'wav_path': str(out_path), 'duration_s': round(duration_s,3), 'status': 'ok'}

    except Exception as exc:
        log.error('Failed %s: %s', row['subject_id'], exc)
        stats['failed'] += 1
        return {'wav_path': '', 'duration_s': 0.0, 'status': f'error:{exc}'}

# ── Run preprocessing ─────────────────────────────────────────────────────────
print('=' * 55)
