    stats  = {'ok': 0, 'skipped': 0, 'failed': 0}
    results = []

    for _, row in tqdm(df.iterrows(), total=len(df), desc='Preprocessing'):
        results.append(process_one(row, stats))

    result_df = pd.DataFrame(results)
    df = pd.concat([df.reset_index(drop=True), result_df], axis=1)
    df.to_csv(MANIFEST_OUT, index=False)

    print(f'\nDone  ok={stats["ok"]}  skipped={stats["skipped"]}  failed={stats["failed"]}')
    print(f'Manifest  → {MANIFEST_OUT}')
    print(f'Audio dir → {OUTPUT_DIR}')
