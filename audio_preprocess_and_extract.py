# AUDIO LOADER
# ─────────────────────────────────────────────────────────────────────────────
def load_wav(path):
    y, sr = sf.read(str(path), dtype='float32')
    if y.ndim > 1:
        y = y.mean(axis=1)
    if sr != SAMPLE_RATE:
        y = librosa.resample(y, orig_sr=sr, target_sr=SAMPLE_RATE)
    return y

# ─────────────────────────────────────────────────────────────────────────────
# GROUP A — PROSODIC FEATURES  (18)
# ─────────────────────────────────────────────────────────────────────────────
def group_a_prosodic(y):
    """
    Pitch (F0) via PYIN, jitter, shimmer, RMS energy statistics,
    voiced ratio, speaking rate, rhythm.

    AD markers: reduced F0 range (monotone speech), higher jitter/shimmer
    (vocal fold instability), slower speaking rate.
    """
    feats = []
    f0, voiced_flag, _ = librosa.pyin(y, fmin=F0_MIN, fmax=F0_MAX,
                                       sr=SAMPLE_RATE, hop_length=HOP_LENGTH)
    voiced_f0 = f0[voiced_flag & ~np.isnan(f0)]

    if len(voiced_f0) > 1:
        feats += [
            float(np.mean(voiced_f0)),
            float(np.std(voiced_f0)),
            float(np.max(voiced_f0) - np.min(voiced_f0)),
            float(np.median(voiced_f0)),
            float(np.percentile(voiced_f0,75) - np.percentile(voiced_f0,25)),
            float(np.mean(np.abs(np.diff(voiced_f0))) / (np.mean(voiced_f0)+1e-9)),  # jitter
        ]
    else:
        feats += [0.0] * 6

    rms = librosa.feature.rms(y=y, frame_length=WIN_LENGTH, hop_length=HOP_LENGTH)[0]
    feats += [
        float(np.mean(rms)), float(np.std(rms)),
        float(np.max(rms)),  float(np.max(rms)-np.min(rms)),
    ]

    # Shimmer — amplitude variation between consecutive voiced frames
    vf_len     = min(len(voiced_flag), len(rms))
    voiced_rms = rms[:vf_len][voiced_flag[:vf_len]]
    shimmer    = float(np.mean(np.abs(np.diff(voiced_rms))) / (np.mean(voiced_rms)+1e-9)) if len(voiced_rms)>1 else 0.0
    feats.append(shimmer)

    duration     = len(y) / SAMPLE_RATE
    voiced_ratio = float(voiced_flag.sum() / max(len(voiced_flag),1))
    speak_rate   = float(voiced_flag.sum() * HOP_LENGTH / SAMPLE_RATE / max(duration,1e-9))
    feats += [voiced_ratio, speak_rate]

    # Rhythm — std and mean of voiced run lengths
    runs, in_run, run_len = [], False, 0
    for v in voiced_flag:
        if v:  in_run, run_len = True, run_len+1
        elif in_run: runs.append(run_len); in_run, run_len = False, 0
    feats += [float(np.mean(runs)) if runs else 0.0,
              float(np.std(runs))  if runs else 0.0]

    return np.array(feats, dtype=np.float32)   # 18

# ─────────────────────────────────────────────────────────────────────────────
# GROUP B — MFCC + SPECTRAL  (189)
# ─────────────────────────────────────────────────────────────────────────────
def group_b_mfcc_spectral(y):
    """
    40 MFCCs (mean+std) + delta (mean) + delta-delta (mean) = 160
    Spectral centroid, bandwidth, rolloff, flatness, ZCR (mean+std each) = 10
    Chroma (12 mean) + Spectral contrast (7 mean) = 19
    Total = 189

    AD markers: altered spectral envelope, reduced high-frequency energy,
    changes in formant-related MFCC patterns.
    """
    mfcc        = librosa.feature.mfcc(y=y, sr=SAMPLE_RATE, n_mfcc=N_MFCC,
                                        n_fft=N_FFT, hop_length=HOP_LENGTH,
                                        win_length=WIN_LENGTH)
    mfcc_d      = librosa.feature.delta(mfcc)
    mfcc_d2     = librosa.feature.delta(mfcc, order=2)
    mfcc_vec    = np.concatenate([
        np.mean(mfcc, axis=1), np.std(mfcc, axis=1),   # 80
        np.mean(mfcc_d,  axis=1),                       # 40
        np.mean(mfcc_d2, axis=1),                       # 40
    ])   # 160

    spec_centroid  = librosa.feature.spectral_centroid(y=y,  sr=SAMPLE_RATE, n_fft=N_FFT, hop_length=HOP_LENGTH)[0]
    spec_bandwidth = librosa.feature.spectral_bandwidth(y=y, sr=SAMPLE_RATE, n_fft=N_FFT, hop_length=HOP_LENGTH)[0]
    spec_rolloff   = librosa.feature.spectral_rolloff(y=y,   sr=SAMPLE_RATE, n_fft=N_FFT, hop_length=HOP_LENGTH)[0]
    spec_flatness  = librosa.feature.spectral_flatness(y=y,  n_fft=N_FFT, hop_length=HOP_LENGTH)[0]
    zcr            = librosa.feature.zero_crossing_rate(y, hop_length=HOP_LENGTH)[0]
    chroma         = librosa.feature.chroma_stft(y=y, sr=SAMPLE_RATE, n_fft=N_FFT, hop_length=HOP_LENGTH)
    contrast       = librosa.feature.spectral_contrast(y=y, sr=SAMPLE_RATE, n_fft=N_FFT, hop_length=HOP_LENGTH)

    spec_vec = np.array([
        np.mean(spec_centroid),  np.std(spec_centroid),
        np.mean(spec_bandwidth), np.std(spec_bandwidth),
        np.mean(spec_rolloff),   np.std(spec_rolloff),
        np.mean(spec_flatness),  np.std(spec_flatness),
        np.mean(zcr),            np.std(zcr),
        *np.mean(chroma, axis=1),    # 12
        *np.mean(contrast, axis=1),  # 7
    ], dtype=np.float32)   # 29

    return np.concatenate([mfcc_vec, spec_vec]).astype(np.float32)   # 189

# ─────────────────────────────────────────────────────────────────────────────
# GROUP C — PAUSE FEATURES  (8)
# ─────────────────────────────────────────────────────────────────────────────
def group_c_pause(y):
    """
    Frame-level RMS energy → dBFS → silence regions → pause events >= 150 ms.
    Internal pauses are intact in the WAV because preprocess_audio only
    trimmed edge silence.

    AD markers: more pauses, longer pauses, higher pause-to-speech ratio,
    pauses at syntactically unexpected positions.
    """
    total_dur = len(y) / SAMPLE_RATE
    rms   = librosa.feature.rms(y=y, frame_length=WIN_LENGTH, hop_length=HOP_LENGTH)[0]
    db    = librosa.amplitude_to_db(rms, ref=np.max(rms+1e-9))
    times = librosa.frames_to_time(np.arange(len(db)), sr=SAMPLE_RATE, hop_length=HOP_LENGTH)

    pause_events, in_pause, p_start = [], False, 0.0
    for t, sil in zip(times, db < PAUSE_DB):
        if sil and not in_pause:
            in_pause, p_start = True, float(t)
        elif not sil and in_pause:
            in_pause = False
            dur = float(t) - p_start
            if dur >= MIN_PAUSE_S:
                pause_events.append(dur)
    if in_pause:
        dur = float(times[-1]) - p_start
        if dur >= MIN_PAUSE_S: pause_events.append(dur)

    n         = len(pause_events)
    tot_pause = sum(pause_events)
    speech_t  = max(total_dur - tot_pause, 0.0)

    return np.array([
        float(n),
        tot_pause,
        float(np.mean(pause_events)) if n > 0 else 0.0,
        float(np.max(pause_events))  if n > 0 else 0.0,
        float(n / (total_dur/60.0))  if total_dur > 0 else 0.0,
        float(tot_pause / speech_t)  if speech_t  > 0 else 0.0,
        speech_t, total_dur,
    ], dtype=np.float32)   # 8

# ─────────────────────────────────────────────────────────────────────────────
# GROUP D — VOICE QUALITY  (6)  [requires Praat]
# ─────────────────────────────────────────────────────────────────────────────
def group_d_voice_quality(y):
    """
    HNR  — Harmonics-to-Noise Ratio
    NHR  — Noise-to-Harmonics Ratio
    Jitter (local) and Shimmer (local) via Praat — more accurate than librosa
    GNE approximation — glottal noise ratio
    Breathiness index

    AD markers: reduced HNR, increased breathiness, irregular glottal pulses.
    """
    if not PRAAT_OK:
        return np.zeros(6, dtype=np.float32)
    try:
        with tempfile.NamedTemporaryFile(suffix='.wav', delete=False) as tmp:
            tmp_path = tmp.name
        sf.write(tmp_path, y, SAMPLE_RATE, subtype='PCM_16')
        snd    = parselmouth.Sound(tmp_path)
        harm   = praat_call(snd, 'To Harmonicity (cc)', 0.01, 75, 0.1, 1.0)
        hnr    = float(praat_call(harm, 'Get mean', 0, 0))
        hnr    = hnr if not np.isnan(hnr) else 0.0
        nhr    = 1.0 / (hnr + 1e-9) if hnr > 0 else 0.0
        pp     = praat_call(snd, 'To PointProcess (periodic, cc)', F0_MIN, F0_MAX)
        jitter = float(praat_call(pp, 'Get jitter (local)', 0,0, 0.0001, 0.02, 1.3))
        shimmer= float(praat_call([snd,pp], 'Get shimmer (local)', 0,0, 0.0001, 0.02, 1.3, 1.6))
        jitter  = jitter  if not np.isnan(jitter)  else 0.0
        shimmer = shimmer if not np.isnan(shimmer) else 0.0
        S       = np.abs(librosa.stft(y, n_fft=N_FFT, hop_length=HOP_LENGTH))
        freqs   = librosa.fft_frequencies(sr=SAMPLE_RATE, n_fft=N_FFT)
        gne     = float(S[freqs>1000].mean() / (S.mean()+1e-9))
        breath  = float(np.std(y) / (np.max(np.abs(y))+1e-9))
        import os; os.unlink(tmp_path)
        return np.array([hnr, nhr, jitter, shimmer, gne, breath], dtype=np.float32)
    except Exception as e:
        log.debug('Voice quality failed: %s', e)
        return np.zeros(6, dtype=np.float32)

# ─────────────────────────────────────────────────────────────────────────────
# GROUP E — ARTICULATION / FORMANTS  (10)  [requires Praat]
# ─────────────────────────────────────────────────────────────────────────────
def group_e_articulation(y):
    """
    F1, F2, F3 mean + std, Vowel Space Area (VSA),
    Formant Centralization Ratio (FCR), Vowel Articulation Index (VAI),
    F1/F2 ratio.

    AD markers: reduced vowel space area (less precise articulation),
    higher FCR (vowel centralisation), lower VAI.
    """
    if not PRAAT_OK:
        return np.zeros(10, dtype=np.float32)
    try:
        with tempfile.NamedTemporaryFile(suffix='.wav', delete=False) as tmp:
            tmp_path = tmp.name
        sf.write(tmp_path, y, SAMPLE_RATE, subtype='PCM_16')
        snd     = parselmouth.Sound(tmp_path)
        formant = praat_call(snd, 'To Formant (burg)', 0.0, 5, 5500, 0.025, 50)
        n_frames= int(praat_call(formant, 'Get number of frames'))
        f1v, f2v, f3v = [], [], []
        for i in range(1, n_frames+1):
            t  = praat_call(formant, 'Get time from frame number', i)
            f1 = praat_call(formant, 'Get value at time', 1, t, 'Hertz', 'Linear')
            f2 = praat_call(formant, 'Get value at time', 2, t, 'Hertz', 'Linear')
            f3 = praat_call(formant, 'Get value at time', 3, t, 'Hertz', 'Linear')
            if not any(np.isnan([f1,f2,f3])):
                f1v.append(f1); f2v.append(f2); f3v.append(f3)
        import os; os.unlink(tmp_path)
        if f1v:
            mf1,sf1 = float(np.mean(f1v)), float(np.std(f1v))
            mf2,sf2 = float(np.mean(f2v)), float(np.std(f2v))
            mf3,sf3 = float(np.mean(f3v)), float(np.std(f3v))
            vsa = float((mf2-mf1)*sf1)
            fcr = float((mf2+mf1)/(mf2+sf2+1e-9))
            vai = float(mf2/(mf1+sf1+1e-9))
            f1f2= float(np.mean(np.array(f1v)/np.array(f2v)))
            return np.array([mf1,sf1,mf2,sf2,mf3,sf3,vsa,fcr,vai,f1f2], dtype=np.float32)
        return np.zeros(10, dtype=np.float32)
    except Exception as e:
        log.debug('Articulation failed: %s', e)
        return np.zeros(10, dtype=np.float32)

# ─────────────────────────────────────────────────────────────────────────────
# GROUP F — TEMPORAL DYNAMICS  (8)
# ─────────────────────────────────────────────────────────────────────────────
def group_f_temporal(y):
    """
    Speech and silence run statistics, speech-silence switch rate.

    AD markers: longer/more variable utterances, irregular speech-silence
    alternation, slower overall communication tempo.
    """
    total_dur = len(y) / SAMPLE_RATE
    rms       = librosa.feature.rms(y=y, frame_length=WIN_LENGTH, hop_length=HOP_LENGTH)[0]
    voiced    = rms > np.mean(rms) * 0.5
    sp_runs, si_runs, in_sp, run = [], [], False, 0
    for v in voiced:
        if v:
            if not in_sp and run>0: si_runs.append(run*HOP_LENGTH/SAMPLE_RATE); run=0
            in_sp, run = True, run+1
        else:
            if in_sp and run>0: sp_runs.append(run*HOP_LENGTH/SAMPLE_RATE); run=0
            in_sp, run = False, run+1
    n_sw = float(len(sp_runs)+len(si_runs))
    return np.array([
        float(np.mean(sp_runs)) if sp_runs else 0.0,
        float(np.std(sp_runs))  if sp_runs else 0.0,
        float(np.mean(si_runs)) if si_runs else 0.0,
        float(np.std(si_runs))  if si_runs else 0.0,
        n_sw,
        float(n_sw / max(total_dur,1e-9)),
        sum(sp_runs), sum(si_runs),
    ], dtype=np.float32)   # 8

# ─────────────────────────────────────────────────────────────────────────────
# GROUP G — DISFLUENCY PROXIES  (4)
# ─────────────────────────────────────────────────────────────────────────────
def group_g_disfluency(y):
    """
    Audio-only proxies for disfluency (exact counts require transcript):
      ZCR bursts       — correlates with fricative/filler phoneme bursts
      Energy bursts    — sudden onsets → filler word starts
      Repetition proxy — short-lag MFCC autocorrelation peak
      Spectral irreg.  — abrupt spectral changes = restarts/corrections

    AD markers: more uh/um fillers, repetitions, self-corrections.
    """
    zcr      = librosa.feature.zero_crossing_rate(y, hop_length=HOP_LENGTH)[0]
    zcr_thr  = np.mean(zcr) + 2*np.std(zcr)
    zcr_b    = float(np.sum(zcr > zcr_thr))

    rms      = librosa.feature.rms(y=y, frame_length=WIN_LENGTH, hop_length=HOP_LENGTH)[0]
    rms_diff = np.diff(rms)
    e_thr    = np.mean(rms_diff) + 2*np.std(rms_diff)
    e_bursts = float(np.sum(rms_diff > e_thr))

    mfcc1    = librosa.feature.mfcc(y=y, sr=SAMPLE_RATE, n_mfcc=1,
                                     n_fft=N_FFT, hop_length=HOP_LENGTH)[0]
    if len(mfcc1) > 30:
        ac   = np.correlate(mfcc1-mfcc1.mean(), mfcc1-mfcc1.mean(), mode='full')
        ac   = ac[len(ac)//2:]; ac /= (ac[0]+1e-9)
        rep  = float(np.max(ac[5:30]))
    else:
        rep  = 0.0

    S        = np.abs(librosa.stft(y, n_fft=N_FFT, hop_length=HOP_LENGTH))
    flux     = np.sqrt(np.sum(np.diff(S, axis=1)**2, axis=0))
    sp_irr   = float(np.std(flux) / (np.mean(flux)+1e-9))

    return np.array([zcr_b, e_bursts, rep, sp_irr], dtype=np.float32)   # 4

# ─────────────────────────────────────────────────────────────────────────────
# GROUP H — WAV2VEC2 EMBEDDINGS  (768)
# ─────────────────────────────────────────────────────────────────────────────
class Wav2Vec2Embedder:
    """Loads model once, extracts mean-pooled 768-d embeddings."""
    def __init__(self):
        log.info('Loading Wav2Vec2 on %s...', DEVICE)
        self.fe    = Wav2Vec2FeatureExtractor.from_pretrained(WAV2VEC_MODEL)
        self.model = Wav2Vec2Model.from_pretrained(WAV2VEC_MODEL).to(DEVICE)
        self.model.eval()
        for p in self.model.parameters(): p.requires_grad = False
        log.info('Wav2Vec2 ready.')

    @torch.no_grad()
    def embed(self, y):
        inp = self.fe(y, sampling_rate=SAMPLE_RATE, return_tensors='pt', padding=False)
        out = self.model(inp.input_values.to(DEVICE))
        return out.last_hidden_state.mean(dim=1).squeeze(0).cpu().numpy().astype(np.float32)  # 768

# ─────────────────────────────────────────────────────────────────────────────
# CONCATENATE ALL GROUPS
# ─────────────────────────────────────────────────────────────────────────────
def extract_all(y, embedder):
    parts, groups = [], {}
    def add(name, vec):
        start = sum(len(p) for p in parts)
        parts.append(vec)
        groups[name] = {'start': start, 'end': start+len(vec), 'size': len(vec)}
    add('A_prosodic',     group_a_prosodic(y))
    add('B_mfcc',         group_b_mfcc_spectral(y))
    add('C_pause',        group_c_pause(y))
    add('D_voice',        group_d_voice_quality(y))
    add('E_articulation', group_e_articulation(y))
    add('F_temporal',     group_f_temporal(y))
    add('G_disfluency',   group_g_disfluency(y))
    add('H_wav2vec2',     embedder.embed(y))
    return np.concatenate(parts).astype(np.float32), groups

