"""## Cell 2 — Parse .cha Files

Extracts `*PAR:` (participant) turns, strips all CHAT annotation codes,  
and saves pause markers separately for Group D feature extraction.
"""

import re, json, logging, warnings
from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from tqdm.notebook import tqdm

warnings.filterwarnings('ignore')
logging.basicConfig(level=logging.INFO,
                    format='%(asctime)s | %(levelname)-8s | %(message)s',
                    datefmt='%H:%M:%S')
log = logging.getLogger(__name__)

# ── Paths ─────────────────────────────────────────────────────────────────────
INPUT_DIR   = Path('/content/drive/MyDrive/pitt_corpus/transcripts')
OUTPUT_DIR  = Path('/content/drive/MyDrive/processed_transcripts')
MANIFEST    = Path('/content/drive/MyDrive/transcript_manifest.csv')

PARTICIPANT_CODE = 'PAR'
TEST_SIZE        = 0.20
RANDOM_STATE     = 42
LABEL_MAP        = {'Dementia': 1, 'Control': 0}

# ── CHAT code regex patterns ───────────────────────────────────────────────────
_RE_RETRACING  = re.compile(r'\[//\]|\[/\]')
_RE_POSTCODES  = re.compile(r'\[[\+\-][^\]]*\]')
_RE_INLINE     = re.compile(r'\[.*?\]')
_RE_ANGLE      = re.compile(r'<[^>]*>')
_RE_NONWORD    = re.compile(r'&[=+\-]?\w+')
_RE_PAUSE_NUM  = re.compile(r'\((\d+\.\d+)\)')    # (1.5)
_RE_PAUSE_DOT  = re.compile(r'\(\.{1,3}\)')        # (.) (..) (...)
_RE_TIMING     = re.compile(r'\d+_\d+')
_RE_UNINTEL    = re.compile(r'\b(xxx|yyy|www)\b', re.IGNORECASE)
_RE_SCOPE      = re.compile(r'[+/\\<>]')
_RE_PROSODY    = re.compile(r'[↑↓⇗⇘∞≈≋≡○●⌊⌋⌈⌉]')
_RE_MULTISPC   = re.compile(r' {2,}')
_RE_SPEAKER    = re.compile(r'^\*(\w+):\s*(.*)')


def extract_pause_markers(raw_turn):
    """Extract pause markers before stripping — returns list of pause dicts."""
    pauses = []
    for i, tok in enumerate(raw_turn.split()):
        m = _RE_PAUSE_NUM.search(tok)
        if m:
            pauses.append({'type': 'numeric', 'duration_s': float(m.group(1)), 'position': i})
        m2 = _RE_PAUSE_DOT.search(tok)
        if m2:
            dots = tok.count('.')
            pauses.append({'type': 'short', 'duration_s': dots * 0.1, 'position': i})
    return pauses


def clean_utterance(raw):
    """Strip all CHAT codes → plain lowercase text."""
    text = raw
    text = _RE_RETRACING.sub('', text)
    text = _RE_POSTCODES.sub('', text)
    text = _RE_INLINE.sub('', text)
    text = _RE_ANGLE.sub('', text)
    text = _RE_NONWORD.sub('', text)
    text = _RE_PAUSE_NUM.sub('', text)
    text = _RE_PAUSE_DOT.sub('', text)
    text = _RE_TIMING.sub('', text)
    text = _RE_UNINTEL.sub('', text)
    text = _RE_SCOPE.sub(' ', text)
    text = _RE_PROSODY.sub('', text)
    text = re.sub(r"[^a-zA-Z0-9 '.,!?]", ' ', text)
    text = _RE_MULTISPC.sub(' ', text).strip().lower()
    return text


def parse_cha(cha_path, speaker=PARTICIPANT_CODE):
    """Parse .cha → (utterances, raw_turns, all_pauses, metadata)."""
    utterances, raw_turns, all_pauses, metadata = [], [], [], {}
    current_speaker, current_turn = None, []

    def flush():
        nonlocal current_speaker, current_turn
        if current_speaker == speaker and current_turn:
            raw    = ' '.join(current_turn)
            pauses = extract_pause_markers(raw)
            for p in pauses:
                p['turn_index'] = len(utterances)
            all_pauses.extend(pauses)
            cleaned = clean_utterance(raw)
            if cleaned:
                raw_turns.append(raw.strip())
                utterances.append(cleaned)
        current_turn.clear()
        current_speaker = None

    with open(cha_path, encoding='utf-8', errors='replace') as fh:
        for line in fh:
            line = line.rstrip('\n')
            if line.startswith('@'):
                flush()
                m = re.match(r'^@(\w+):\s*(.*)', line)
                if m: metadata[m.group(1)] = m.group(2).strip()
                continue
            if line.startswith('%'):
                continue
            m = _RE_SPEAKER.match(line)
            if m:
                flush()
                current_speaker = m.group(1).upper()
                current_turn    = [m.group(2)]
                continue
            if line.startswith(('\t', ' ')) and current_speaker:
                current_turn.append(line.strip())
    flush()
    return utterances, raw_turns, all_pauses, metadata


def discover_files(input_dir):
    records = []
    for label_str in LABEL_MAP:
        folder = input_dir / label_str
        if not folder.exists():
            log.warning('Folder not found: %s', folder)
            continue
        for cha in sorted(folder.glob('*.cha')):
            records.append({'subject_id': cha.stem, 'raw_path': str(cha),
                            'label_str': label_str, 'label': LABEL_MAP[label_str]})
    df = pd.DataFrame(records)
    log.info('Found %d files  (Dem=%d  Ctrl=%d)',
             len(df), (df.label==1).sum(), (df.label==0).sum())
    return df


def stratified_split(df):
    _, test_df = train_test_split(df, test_size=TEST_SIZE,
                                  stratify=df['label'], random_state=RANDOM_STATE)
    df = df.copy()
    df['split'] = 'train'
    df.loc[test_df.index, 'split'] = 'test'
    log.info('Split → train=%d  test=%d',
             (df.split=='train').sum(), (df.split=='test').sum())
    return df


def process_one(row, stats):
    sid     = row['subject_id']
    out_dir = OUTPUT_DIR / row['split'] / row['label_str']
    out_dir.mkdir(parents=True, exist_ok=True)
    try:
        utts, raw_turns, pauses, meta = parse_cha(row['raw_path'])
        if not utts:
            stats['skipped'] += 1
            return {'clean_path': '', 'pause_path': '',
                    'n_utterances': 0, 'n_tokens': 0, 'n_pauses': 0,
                    'status': 'skipped_no_utterances'}

        full_clean = ' '.join(utts)
        n_tokens   = len(full_clean.split())

        clean_path = out_dir / f'{sid}.txt'
        clean_path.write_text(full_clean, encoding='utf-8')

        pause_data = {
            'subject_id':    sid,
            'label':         row['label'],
            'label_str':     row['label_str'],
            'split':         row['split'],
            'n_utterances':  len(utts),
            'n_pauses':      len(pauses),
            'total_pause_s': round(sum(p['duration_s'] for p in pauses), 3),
            'pause_events':  pauses,
        }
        pause_path = out_dir / f'{sid}_pauses.json'
        pause_path.write_text(json.dumps(pause_data, indent=2), encoding='utf-8')

        stats['ok'] += 1
        return {'clean_path': str(clean_path), 'pause_path': str(pause_path),
                'n_utterances': len(utts), 'n_tokens': n_tokens,
                'n_pauses': len(pauses), 'status': 'ok'}
    except Exception as exc:
        log.error('Failed %s: %s', sid, exc)
        stats['failed'] += 1
        return {'clean_path': '', 'pause_path': '',
                'n_utterances': 0, 'n_tokens': 0, 'n_pauses': 0,
                'status': f'error:{exc}'}


