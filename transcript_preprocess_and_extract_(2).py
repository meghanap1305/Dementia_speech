"""## Cell 4 — Dataset

This `Dataset` class loads the preprocessed transcript text and the extracted hand-crafted features (Groups A-G) for each subject. It will be used in the training pipeline to prepare data for the model.

Each `__getitem__` call will load:
1. The **raw transcript text** (`.txt`) — tokenised and fed live to DistilRoBERTa
2. **Hand-crafted features A–G** from `.npz` (group H excluded — computed live)
"""

import torch
from torch.utils.data import Dataset

class TranscriptDataset(Dataset):
    def __init__(self, manifest_df, feature_groups):
        self.manifest_df    = manifest_df.reset_index(drop=True)
        self.feature_groups = feature_groups

    def __len__(self):
        return len(self.manifest_df)

    def __getitem__(self, idx):
        row         = self.manifest_df.iloc[idx]
        subject_id  = row['subject_id']
        clean_path  = row['clean_path']
        feature_path = row['feature_path']
        label       = row['label']

        # Load raw text
        text = Path(clean_path).read_text(encoding='utf-8')

        # Load features (A-G)
        all_features = np.load(feature_path)['features']

        # Exclude DistilRoBERTa features (Group H) as they will be recomputed live
        # This assumes H_distilroberta is the last group in the feature_groups dict
        h_start_idx = self.feature_groups['H_distilroberta']['start']
        hand_crafted_features = all_features[:h_start_idx]

        return {
            'subject_id': subject_id,
            'text':       text,
            'features':   torch.from_numpy(hand_crafted_features).float(),
            'label':      torch.tensor(label, dtype=torch.long)
        }

print('TranscriptDataset class defined.')

