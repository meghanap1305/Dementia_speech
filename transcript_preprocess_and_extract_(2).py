"""## Cell 3 — Feature Extraction

| Group | Features | Count |
|---|---|---|
| A | Lexical richness — TTR, MATTR, Brunet W, Honoré R, hapax ratio, density | 8 |
| B | Syntactic — MLU, POS ratios, arc length, tokens/sentence | 10 |
| C | Semantic — content density, filler rate, empty phrase, entity | 6 |
| D | Pause/disfluency — count, duration, rate, numeric/short split | 10 |
| E | Discourse — repetition, bigram overlap, informativeness, coherence | 8 |
| F | Sentiment/affect — polarity, subjectivity, uncertainty, hedge | 6 |
| G | Readability — Flesch, SMOG, Fog, avg word/sent length, syllables | 8 |
| H | **DistilRoBERTa** — 768-d CLS token from `distilroberta-base` | 768 |
| | **Total** | **824** |
"""

import torch
import spacy
import textstat
from collections import Counter
from nltk.tokenize import word_tokenize, sent_tokenize
from nltk.corpus import stopwords
from textblob import TextBlob
from transformers import AutoTokenizer, AutoModel

nlp        = spacy.load('en_core_web_sm')
STOP_WORDS = set(stopwords.words('english'))
DEVICE     = 'cuda' if torch.cuda.is_available() else 'cpu'
print(f'Device: {DEVICE}')

# ── Output paths ──────────────────────────────────────────────────────────────
FEAT_OUTPUT_DIR  = Path('/content/transcript_features')
FEAT_MANIFEST    = Path('/content/transcript_feature_manifest.csv')
FEAT_GROUPS_FILE = Path('/content/transcript_feature_groups.json')

# ── DistilRoBERTa model name ───────────────────────────────────────────────────
DISTILROBERTA_MODEL = 'distilroberta-base'


# ─────────────────────────────────────────────────────────────────────────────
# GROUP A — LEXICAL RICHNESS  (8)
# AD markers: reduced TTR (repetitive vocabulary), fewer hapax legomena,
# lower lexical density (more function words, fewer content words)
# ─────────────────────────────────────────────────────────────────────────────
def group_a_lexical(text):
    tokens = word_tokenize(text.lower())
    words  = [t for t in tokens if t.isalpha()]
    if not words:
        return np.zeros(8, dtype=np.float32)
    N, V   = len(words), len(set(words))
    ttr    = V / N

    # MATTR — moving average TTR (window=25, corrects for length sensitivity)
    win    = 25
    mattr  = float(np.mean([len(set(words[i:i+win]))/win
                             for i in range(N-win+1)])) if N >= win else ttr

    # Brunet's W — lower = richer vocabulary
    brunet = float(N ** (V ** -0.165)) if V > 0 else 0.0

    # Honoré's R
    freq   = Counter(words)
    hapax  = sum(1 for c in freq.values() if c == 1)
    honore = float(100 * np.log(N) / (1 - hapax/V)) if (V > hapax and N > 1) else 0.0
    hapax_ratio = hapax / V if V > 0 else 0.0

    # Lexical density (content words / all words)
    doc         = nlp(text[:5000])
    content_pos = {'NOUN','VERB','ADJ','ADV'}
    content_n   = sum(1 for t in doc if t.pos_ in content_pos and t.is_alpha)
    lex_density = content_n / max(sum(1 for t in doc if t.is_alpha), 1)

    return np.array([ttr, mattr, brunet, honore, float(N), float(V),
                     hapax_ratio, lex_density], dtype=np.float32)  # 8


# ─────────────────────────────────────────────────────────────────────────────
# GROUP B — SYNTACTIC FEATURES  (10)
# AD markers: shorter MLU, simpler grammar, higher pronoun-noun ratio
# (vague reference instead of naming objects)
# ─────────────────────────────────────────────────────────────────────────────
def group_b_syntactic(text):
    doc   = nlp(text[:8000])
    sents = list(doc.sents)
    if not sents:
        return np.zeros(10, dtype=np.float32)

    sent_lens = [len([t for t in s if t.is_alpha]) for s in sents]
    mlu       = float(np.mean(sent_lens))
    mlu_std   = float(np.std(sent_lens))

    tokens    = [t for t in doc if t.is_alpha]
    N         = max(len(tokens), 1)
    pos_count = Counter(t.pos_ for t in tokens)

    noun_r = pos_count.get('NOUN', 0) / N
    verb_r = pos_count.get('VERB', 0) / N
    pron_r = pos_count.get('PRON', 0) / N
    adj_r  = pos_count.get('ADJ',  0) / N
    adv_r  = pos_count.get('ADV',  0) / N

    # Average dependency arc length — longer = more complex syntax
    arc_lens = [abs(t.i - t.head.i) for t in doc if t.dep_ != 'ROOT']
    avg_arc  = float(np.mean(arc_lens)) if arc_lens else 0.0

    n_sents      = float(len(sents))
    tok_per_sent = float(N) / max(n_sents, 1)

    return np.array([mlu, mlu_std, n_sents, noun_r, verb_r,
                     pron_r, adj_r, adv_r, avg_arc, tok_per_sent],
                    dtype=np.float32)  # 10


# ─────────────────────────────────────────────────────────────────────────────
# GROUP C — SEMANTIC FEATURES  (6)
# AD markers: more empty speech, higher pronoun-noun ratio,
# more filler words, lower content density
# ─────────────────────────────────────────────────────────────────────────────
def group_c_semantic(text):
    doc    = nlp(text[:8000])
    tokens = [t for t in doc if t.is_alpha]
    N      = max(len(tokens), 1)

    content_pos = {'NOUN','VERB','ADJ','ADV'}
    content_den = sum(1 for t in tokens if t.pos_ in content_pos) / N

    empty_words = {'it','thing','stuff','something','anything','everything','one'}
    empty_ratio = sum(1 for t in tokens if t.lower_ in empty_words) / N

    avg_wlen    = float(np.mean([len(t.text) for t in tokens]))

    ent_ratio   = len(doc.ents) / max(len(list(doc.sents)), 1)

    nouns  = sum(1 for t in tokens if t.pos_ == 'NOUN')
    prons  = sum(1 for t in tokens if t.pos_ == 'PRON')
    pn_ratio = prons / max(nouns, 1)

    fillers  = {'uh','um','er','ah','well','like'}
    fill_r   = sum(1 for t in tokens if t.lower_ in fillers) / N

    return np.array([content_den, empty_ratio, avg_wlen,
                     float(ent_ratio), pn_ratio, fill_r],
                    dtype=np.float32)  # 6


# ─────────────────────────────────────────────────────────────────────────────
# GROUP D — PAUSE / DISFLUENCY  (10)
# Derived from the pause log saved during .cha parsing (Cell 2)
# AD markers: more pauses, longer pauses, more mid-utterance pauses
# ─────────────────────────────────────────────────────────────────────────────
def group_d_pause(pause_json_path):
    try:
        data   = json.loads(Path(pause_json_path).read_text())
        events = data.get('pause_events', [])
        n_utt  = max(data.get('n_utterances', 1), 1)
    except Exception:
        return np.zeros(10, dtype=np.float32)

    n_p     = len(events)
    durs    = [e['duration_s'] for e in events]
    tot_p   = sum(durs)
    mean_p  = float(np.mean(durs)) if durs else 0.0
    max_p   = float(np.max(durs))  if durs else 0.0
    std_p   = float(np.std(durs))  if durs else 0.0
    p_rate  = n_p / n_utt

    num_p   = sum(1 for e in events if e['type'] == 'numeric')
    short_p = sum(1 for e in events if e['type'] == 'short')
    num_r   = num_p   / max(n_p, 1)
    short_r = short_p / max(n_p, 1)

    return np.array([float(n_p), tot_p, mean_p, max_p, std_p,
                     p_rate, num_r, short_r, float(num_p), float(short_p)],
                    dtype=np.float32)  # 10


# ─────────────────────────────────────────────────────────────────────────────
# GROUP E — DISCOURSE FEATURES  (8)
# AD markers: more repetition, lower informativeness, fragmented sentences,
# less use of discourse connectives
# ─────────────────────────────────────────────────────────────────────────────
def group_e_discourse(text):
    sents  = sent_tokenize(text)
    n_s    = max(len(sents), 1)
    tokens = word_tokenize(text.lower())
    words  = [t for t in tokens if t.isalpha() and t not in STOP_WORDS]
    N      = max(len(words), 1)

    freq      = Counter(words)
    rep_ratio = sum(c-1 for c in freq.values() if c>1) / N

    def bigrams(s):
        w = word_tokenize(s.lower())
        return set(zip(w, w[1:]))
    overlaps = []
    for i in range(len(sents)-1):
        bg1, bg2 = bigrams(sents[i]), bigrams(sents[i+1])
        denom    = max(len(bg1|bg2), 1)
        overlaps.append(len(bg1&bg2) / denom)
    sent_overlap    = float(np.mean(overlaps)) if overlaps else 0.0

    informativeness = len(freq) / N
    slen_std        = float(np.std([len(word_tokenize(s)) for s in sents])) if n_s>1 else 0.0
    q_ratio         = sum(1 for s in sents if s.strip().endswith('?')) / n_s
    short_sent      = sum(1 for s in sents if len(word_tokenize(s)) < 4) / n_s

    connectives = {'and','but','so','because','then','also','however',
                   'therefore','although','while','since','when','if'}
    conn_ratio  = sum(1 for t in tokens if t in connectives) / max(len(tokens), 1)

    return np.array([rep_ratio, sent_overlap, informativeness, slen_std,
                     q_ratio, short_sent, conn_ratio, float(n_s)],
                    dtype=np.float32)  # 8


# ─────────────────────────────────────────────────────────────────────────────
# GROUP F — SENTIMENT / AFFECT  (6)
# AD markers: reduced emotional expressiveness, more uncertainty language,
# more hedging (reflects word-finding difficulty and low confidence)
# ─────────────────────────────────────────────────────────────────────────────
def group_f_sentiment(text):
    try:
        tb   = TextBlob(text)
        pol  = float(tb.sentiment.polarity)
        subj = float(tb.sentiment.subjectivity)
    except Exception:
        pol, subj = 0.0, 0.0

    tokens = word_tokenize(text.lower())
    N      = max(len(tokens), 1)

    pos_words  = {'good','nice','happy','love','beautiful','wonderful','great'}
    neg_words  = {'bad','sad','terrible','awful','hate','horrible','wrong'}
    uncertainty= {'maybe','perhaps','possibly','might','think','guess',
                  'suppose','probably','seem','appear','feel'}
    hedge_wds  = {'kind of','sort of','a bit','rather','quite','somewhat','fairly'}

    text_l = text.lower()
    pos_r  = sum(1 for t in tokens if t in pos_words)   / N
    neg_r  = sum(1 for t in tokens if t in neg_words)   / N
    unc_r  = sum(1 for t in tokens if t in uncertainty) / N
    hedge_r= sum(1 for h in hedge_wds if h in text_l) / len(hedge_wds)

    return np.array([pol, subj, pos_r, neg_r, unc_r, hedge_r],
                    dtype=np.float32)  # 6


# ─────────────────────────────────────────────────────────────────────────────
# GROUP G — READABILITY  (8)
# AD markers: simpler sentence structure, shorter words, lower grade level
# ─────────────────────────────────────────────────────────────────────────────
def group_g_readability(text):
    try:
        fre  = float(textstat.flesch_reading_ease(text))
        fkg  = float(textstat.flesch_kincaid_grade(text))
        smog = float(textstat.smog_index(text))
        fog  = float(textstat.gunning_fog(text))
    except Exception:
        fre = fkg = smog = fog = 0.0

    tokens  = [t for t in word_tokenize(text.lower()) if t.isalpha()]
    N       = max(len(tokens), 1)
    sents   = sent_tokenize(text)
    avg_wl  = float(np.mean([len(t) for t in tokens]))
    avg_sl  = float(N / max(len(sents), 1))

    def count_syl(w):
        return max(1, len(re.findall(r'[aeiouy]+', w.lower())))
    avg_syl = float(np.mean([count_syl(t) for t in tokens]))
    long_r  = sum(1 for t in tokens if len(t) > 6) / N

    return np.array([fre, fkg, smog, fog, avg_wl, avg_sl, avg_syl, long_r],
                    dtype=np.float32)  # 8


# ─────────────────────────────────────────────────────────────────────────────
# GROUP H — DistilRoBERTa EMBEDDINGS  (768)
# distilroberta-base: 82M params, 40% smaller than roberta-base,
# same 768-d hidden size, better than BERT on short/informal text
# ─────────────────────────────────────────────────────────────────────────────
class DistilRoBERTaEmbedder:
    """
    Loads distilroberta-base once.
    Returns 768-d CLS token embedding per transcript.

    Why distilroberta-base over bert-base-uncased?
    - RoBERTa training: dynamic masking, no NSP, longer training
    - 40% fewer params → faster, less VRAM pressure on Colab
    - Handles fragmented, colloquial speech transcripts better
    - Uses BPE tokenisation — better for non-standard words in AD speech
    """
    MAX_TOKENS = 512

    def __init__(self):
        log.info('Loading DistilRoBERTa on %s...', DEVICE)
        self.tokenizer = AutoTokenizer.from_pretrained(DISTILROBERTA_MODEL)
        self.model     = AutoModel.from_pretrained(DISTILROBERTA_MODEL).to(DEVICE)
        self.model.eval()
        for p in self.model.parameters(): p.requires_grad = False
        log.info('DistilRoBERTa ready.')

    @torch.no_grad()
    def embed(self, text):
        enc = self.tokenizer(
            text,
            max_length=self.MAX_TOKENS,
            truncation=True,
            padding='max_length',
            return_tensors='pt',
        )
        out = self.model(
            input_ids=enc.input_ids.to(DEVICE),
            attention_mask=enc.attention_mask.to(DEVICE),
        )
        # CLS token = first token of last hidden state
        return out.last_hidden_state[:, 0, :].squeeze(0).cpu().numpy().astype(np.float32)


# ─────────────────────────────────────────────────────────────────────────────
# COMBINE ALL GROUPS
# ─────────────────────────────────────────────────────────────────────────────
def extract_all(text, pause_path, embedder):
    parts, groups = [], {}
    def add(name, vec):
        start = sum(len(p) for p in parts)
        parts.append(vec)
        groups[name] = {'start': start, 'end': start+len(vec), 'size': len(vec)}
    add('A_lexical',       group_a_lexical(text))
    add('B_syntactic',     group_b_syntactic(text))
    add('C_semantic',      group_c_semantic(text))
    add('D_pause',         group_d_pause(pause_path))
    add('E_discourse',     group_e_discourse(text))
    add('F_sentiment',     group_f_sentiment(text))
    add('G_readability',   group_g_readability(text))
    add('H_distilroberta', embedder.embed(text))
    return np.concatenate(parts).astype(np.float32), groups


