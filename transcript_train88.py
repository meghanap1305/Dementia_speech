"""## §5 · Model Architecture

### 5.1 Overview

```
Raw transcript text
        ↓  HuggingFace tokeniser (max 512 tokens, WordPiece)
  DistilRoBERTa-base  (82 M params, 6 transformer layers)
    · Embeddings             ← FROZEN
    · Transformer layers 0–2 ← FROZEN   (preserve general language knowledge)
    · Transformer layers 3–5 ← FINE-TUNED @ lr=2e-5
        ↓  CLS token
     768-d text embedding
        |
  Hand-crafted features A–G (56-d)
        ↓  Clinical MLP: Linear(56→64) → LayerNorm → GELU → Dropout
                         Linear(64→32) → LayerNorm → GELU
     32-d clinical embedding
        |
  Concat [768 + 32 = 800-d]
        ↓  Fusion Classifier:
           LayerNorm(800) → Dropout → Linear(800→256) → GELU
           → Dropout → Linear(256→64) → GELU
           → Dropout → Linear(64→2)
  Logits [batch, 2] → Focal Loss / Softmax
```

### 5.2 Design Rationale

| Choice | Justification |
|---|---|
| DistilRoBERTa over BERT | 40 % fewer parameters; comparable performance; faster iteration |
| Freeze layers 0–2 | Preserve general syntax/morphology; avoid catastrophic forgetting on small dataset |
| Fine-tune layers 3–5 | Learn domain-specific discourse patterns (repetition, tangentiality) |
| Clinical MLP branch | Encodes interpretable linguistic features shown predictive in prior work |
| Focal Loss γ=2 | Down-weights easy Control samples; focuses on hard AD cases |
| Differential LR | Backbone at 2e-5 avoids over-fitting; heads at 1e-4 for faster convergence |
| Threshold tuning | Dataset imbalance means default 0.5 is not optimal; sweep identifies best boundary |

"""

# ── Focal Loss ────────────────────────────────────────────────────────────────
class FocalLoss(nn.Module):
    r"""
    Focal Loss for binary classification with class weights and label smoothing.

    FL(p_t) = -α_t · (1 − p_t)^γ · log(p_t)

    Parameters
    ----------
    gamma : float
        Focusing parameter. γ=0 → standard cross-entropy; γ=2 (default)
        strongly down-weights well-classified examples.
    weight : Tensor or None
        Per-class weights (passed to F.cross_entropy).
    label_smoothing : float
        ε for label smoothing regularisation.
    """

    def __init__(self, gamma: float = 2.0, weight=None, label_smoothing: float = 0.0):
        super().__init__()
        self.gamma           = gamma
        self.weight          = weight
        self.label_smoothing = label_smoothing

    def forward(self, logits: torch.Tensor, targets: torch.Tensor) -> torch.Tensor:
        ce_loss = F.cross_entropy(
            logits, targets,
            weight=self.weight,
            label_smoothing=self.label_smoothing,
            reduction='none',
        )
        p_t = torch.softmax(logits, dim=1).gather(1, targets.unsqueeze(1)).squeeze(1)
        return ((1.0 - p_t) ** self.gamma * ce_loss).mean()


# ── End-to-end multimodal AD classifier ───────────────────────────────────────
class ADTranscriptModel(nn.Module):
    """
    End-to-end multimodal model for Alzheimer's disease detection.

    Combines a fine-tuned DistilRoBERTa backbone (text branch) with a
    hand-crafted clinical feature branch; outputs are fused via a 3-layer
    MLP classifier.

    Parameters
    ----------
    n_clinical : int
        Dimensionality of hand-crafted clinical features (A–G; 56 by default).
    dropout : float
        Dropout probability applied in the clinical MLP and fusion classifier.
    """

    def __init__(self, n_clinical: int, dropout: float = DROPOUT):
        super().__init__()
        self.roberta = AutoModel.from_pretrained(BACKBONE)
        hidden_size  = self.roberta.config.hidden_size          # 768

        # Freeze embedding layer
        for p in self.roberta.embeddings.parameters():
            p.requires_grad = False

        # Freeze bottom FREEZE_LAYERS transformer blocks
        for i in range(FREEZE_LAYERS):
            for p in self.roberta.encoder.layer[i].parameters():
                p.requires_grad = False

        # Clinical feature branch: 56 → 64 → 32
        self.clinical_mlp = nn.Sequential(
            nn.Linear(n_clinical, 64), nn.LayerNorm(64), nn.GELU(), nn.Dropout(dropout),
            nn.Linear(64, 32),         nn.LayerNorm(32), nn.GELU(),
        )

        # Fusion classifier: 800 → 256 → 64 → 2
        fusion_dim = hidden_size + 32
        self.classifier = nn.Sequential(
            nn.LayerNorm(fusion_dim),
            nn.Dropout(dropout),
            nn.Linear(fusion_dim, 256), nn.GELU(),
            nn.Dropout(dropout / 2),
            nn.Linear(256, 64),         nn.GELU(),
            nn.Dropout(dropout / 2),
            nn.Linear(64, 2),
        )

        # Xavier initialisation for linear layers in the task-specific heads
        for module in [self.clinical_mlp, self.classifier]:
            for m in module.modules():
                if isinstance(m, nn.Linear):
                    nn.init.xavier_uniform_(m.weight)
                    if m.bias is not None:
                        nn.init.zeros_(m.bias)

    def forward(
        self,
        input_ids: torch.Tensor,
        attention_mask: torch.Tensor,
        clinical_feats: torch.Tensor,
    ) -> torch.Tensor:
        # Text branch — fine-tuned DistilRoBERTa CLS token
        out     = self.roberta(input_ids=input_ids, attention_mask=attention_mask)
        cls_emb = out.last_hidden_state[:, 0, :]        # [B, 768]
        # Clinical branch
        clin    = self.clinical_mlp(clinical_feats)     # [B, 32]
        # Late fusion + classification
        fused   = torch.cat([cls_emb, clin], dim=-1)   # [B, 800]
        return self.classifier(fused)                  # [B, 2]


