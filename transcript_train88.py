# ── Training utilities ────────────────────────────────────────────────────────

def train_epoch(model, loader, optimizer, criterion, scaler_amp, scheduler):
    model.train()
    total_loss, preds, lbls = 0., [], []
    optimizer.zero_grad()
    for step, batch in enumerate(loader):
        ids = batch['input_ids'].to(DEVICE)
        am  = batch['attention_mask'].to(DEVICE)
        cf  = batch['clinical_feats'].to(DEVICE)
        y   = batch['label'].to(DEVICE)
        with autocast():
            logits = model(ids, am, cf)
            loss   = criterion(logits, y) / GRAD_ACCUM
        scaler_amp.scale(loss).backward()
        if (step + 1) % GRAD_ACCUM == 0:
            scaler_amp.unscale_(optimizer)
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            scaler_amp.step(optimizer)
            scaler_amp.update()
            scheduler.step()
            optimizer.zero_grad()
        total_loss += loss.item() * GRAD_ACCUM
        preds.extend(logits.argmax(1).detach().cpu().tolist())
        lbls.extend(y.cpu().tolist())
    return {
        'loss': total_loss / len(loader),
        'acc':  accuracy_score(lbls, preds),
        'f1':   f1_score(lbls, preds, zero_division=0),
    }


@torch.no_grad()
def eval_epoch(model, loader, criterion, threshold: float = 0.5):
    model.eval()
    total_loss, lbls, probs = 0., [], []
    for batch in loader:
        ids = batch['input_ids'].to(DEVICE)
        am  = batch['attention_mask'].to(DEVICE)
        cf  = batch['clinical_feats'].to(DEVICE)
        y   = batch['label'].to(DEVICE)
        with autocast():
            logits = model(ids, am, cf)
        total_loss += criterion(logits.float(), y).item()
        probs.extend(torch.softmax(logits, 1)[:, 1].cpu().tolist())
        lbls.extend(y.cpu().tolist())
    preds = [1 if p >= threshold else 0 for p in probs]
    try:
        auroc = roc_auc_score(lbls, probs)
    except Exception:
        auroc = 0.0
    return {
        'loss':   total_loss / len(loader),
        'acc':    accuracy_score(lbls, preds),
        'f1':     f1_score(lbls, preds, zero_division=0),
        'auroc':  auroc,
        'preds':  preds,
        'labels': lbls,
        'probs':  probs,
    }


