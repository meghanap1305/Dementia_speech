class PittTranscriptDataset(Dataset):
    """
    DementiaBank Pitt Corpus — Cookie Theft transcript dataset.

    Parameters
    ----------
    df : pd.DataFrame
        Manifest rows for this split.
    transcript_dir : Path or None
        Directory tree: <transcript_dir>/<split>/<label_str>/<subject_id>.txt
        If None or missing, falls back to same directory as .npz.
    scaler : StandardScaler or None
        Pre-fit scaler; if fit_scaler=True it is fit in-place.
    fit_scaler : bool
        Fit the scaler on this split's clinical features (train only).

    Returns (per item)
    ------------------
    input_ids      : LongTensor [MAX_TOKEN_LEN]
    attention_mask : LongTensor [MAX_TOKEN_LEN]
    clinical_feats : FloatTensor [N_CLINICAL]
    label          : LongTensor []
    """

    def __init__(self, df, transcript_dir, scaler=None, fit_scaler=False):
        self.df             = df.reset_index(drop=True)
        self.transcript_dir = Path(transcript_dir) if transcript_dir else None

        all_feats, labels, valid_idx = [], [], []
        self.texts = []

        for idx, row in self.df.iterrows():
            npz_path = Path(row['feature_path'])
            txt_path = self._build_txt_path(row)

            if not npz_path.exists():
                print(f'  SKIP (no .npz): {row["subject_id"]}')
                continue
            if not txt_path.exists():
                print(f'  SKIP (no .txt): {txt_path}')
                continue

            data     = np.load(str(npz_path))
            fv       = data['features']
            clinical = np.concatenate([fv[:H_START], fv[H_END:]])
            all_feats.append(clinical)
            labels.append(int(data['label']))
            valid_idx.append(idx)
            self.texts.append(txt_path.read_text(encoding='utf-8').strip())

        self.df   = self.df.loc[valid_idx].reset_index(drop=True)
        all_feats = np.nan_to_num(
            np.stack(all_feats).astype(np.float32),
            nan=0., posinf=0., neginf=0.
        )

        if fit_scaler and scaler:
            scaler.fit(all_feats)
        if scaler:
            all_feats = scaler.transform(all_feats).astype(np.float32)

        self.clinical = torch.tensor(all_feats, dtype=torch.float32)
        self.labels   = torch.tensor(labels,    dtype=torch.long)

        split = self.df['split'].iloc[0] if len(self.df) else 'unknown'
        dem   = (self.labels == 1).sum().item()
        ctrl  = (self.labels == 0).sum().item()
        print(f'[{split:5s}] {len(self.labels)} samples  '
              f'Dementia={dem}  Control={ctrl}  '
              f'AD%={100*dem/len(self.labels):.1f}%')

    def _build_txt_path(self, row):
        if self.transcript_dir and self.transcript_dir.exists():
            return (self.transcript_dir / row['split']
                    / row['label_str'] / (row['subject_id'] + '.txt'))
        return Path(row['feature_path']).parent / (Path(row['feature_path']).stem + '.txt')

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        enc = tokenizer(
            self.texts[idx],
            max_length=MAX_TOKEN_LEN,
            truncation=True,
            padding='max_length',
            return_tensors='pt',
        )
        return {
            'input_ids':      enc.input_ids.squeeze(0),
            'attention_mask': enc.attention_mask.squeeze(0),
            'clinical_feats': self.clinical[idx],
            'label':          self.labels[idx],
        }


