# ── Bootstrap 95% Confidence Intervals ───────────────────────────────────────
def bootstrap_ci(y_true, y_prob, metric_fn, n_boot=10000, ci=0.95, thr=0.5):
    rng    = np.random.default_rng(SEED)
    n      = len(y_true)
    scores = []
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        scores.append(metric_fn(y_true[idx], y_prob[idx], thr))
    lo = np.percentile(scores, 100 * (1 - ci) / 2)
    hi = np.percentile(scores, 100 * (1 - (1 - ci) / 2))
    return lo, hi

def _f1(yt, yp, thr):
    return f1_score(yt, (yp >= thr).astype(int), zero_division=0)
def _acc(yt, yp, thr):
    return accuracy_score(yt, (yp >= thr).astype(int))
def _auroc(yt, yp, thr):
    try: return roc_auc_score(yt, yp)
    except: return float('nan')
def _sens(yt, yp, thr):
    return recall_score(yt, (yp >= thr).astype(int), pos_label=1, zero_division=0)
def _spec(yt, yp, thr):
    p = (yp >= thr).astype(int)
    cm_ = confusion_matrix(yt, p)
    return cm_[0,0] / max(cm_[0,0]+cm_[0,1], 1)

