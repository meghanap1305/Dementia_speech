# ── Ablation helper ───────────────────────────────────────────────────────────

def run_ablation(name, override_cfg):
    """
    Train a model variant with overridden settings and return val-set metrics.
    override_cfg: dict of changes, e.g. {'use_clinical': False}
    """
    print(f'\n  Running ablation: {name}')
    cfg = dict(
        use_clinical    = True,    # If False, zero out clinical features
        focal_gamma     = FOCAL_GAMMA,
        label_smooth    = LABEL_SMOOTH,
        freeze_layers   = FREEZE_LAYERS,
        diff_lr         = True,    # If False, use single LR for all params
        lr_backbone     = LR_BACKBONE,
        lr_head         = LR_HEAD,
    )
    cfg.update(override_cfg)

    # Dataset (reuse train_ds and test_ds as train/val for ablation)
    ab_train_loader = train_loader
    ab_val_loader   = test_loader

    # Class weights (use train_ds for weights calculation)
    n_d  = (train_ds.labels == 1).sum().item()
    n_c  = (train_ds.labels == 0).sum().item()
    w_c  = (n_d + n_c) / (2.0 * n_c)
    w_d  = (n_d + n_c) / (2.0 * n_d) * DEM_WEIGHT_BOOST
    ab_weights = torch.tensor([w_c, w_d], dtype=torch.float32).to(DEVICE)

    # Model
    ab_model = ADTranscriptModel(N_CLINICAL).to(DEVICE)

    # Override freeze layers
    if cfg['freeze_layers'] != FREEZE_LAYERS:
        # First unfreeze all
        for p in ab_model.roberta.parameters():
            p.requires_grad = True
        # Re-freeze embeddings
        for p in ab_model.roberta.embeddings.parameters():
            p.requires_grad = False
        # Freeze requested layers
        for i in range(cfg['freeze_layers']):
            for p in ab_model.roberta.encoder.layer[i].parameters():
                p.requires_grad = False

    # Loss
    if cfg['focal_gamma'] == 0:
        ab_crit = nn.CrossEntropyLoss(weight=ab_weights,
                                       label_smoothing=cfg['label_smooth'])
    else:
        ab_crit = FocalLoss(gamma=cfg['focal_gamma'], weight=ab_weights,
                             label_smoothing=cfg['label_smooth'])

    # Optimizer
    if cfg['diff_lr']:
        bb_p = [p for n, p in ab_model.named_parameters()
                if 'roberta' in n and p.requires_grad]
        hd_p = [p for n, p in ab_model.named_parameters()
                if 'roberta' not in n and p.requires_grad]
        ab_opt = torch.optim.AdamW(
            [{'params': bb_p, 'lr': cfg['lr_backbone']},
             {'params': hd_p, 'lr': cfg['lr_head']}],
            weight_decay=WEIGHT_DECAY)
    else:
        ab_opt = torch.optim.AdamW(ab_model.parameters(),
                                    lr=LR_HEAD, weight_decay=WEIGHT_DECAY)

    n_st  = (len(ab_train_loader) // GRAD_ACCUM) * NUM_EPOCHS
    n_wm  = int(n_st * WARMUP_RATIO)
    ab_sched = get_linear_schedule_with_warmup(ab_opt, n_wm, n_st)
    ab_amp   = GradScaler()

    best_ab_f1, best_ab_state, ab_pat = 0., None, 0

    for epoch in range(1, NUM_EPOCHS + 1):
        # Train (with optional clinical zeroing)
        ab_model.train()
        ab_opt.zero_grad()
        for step, batch in enumerate(ab_train_loader):
            ids = batch['input_ids'].to(DEVICE)
            am  = batch['attention_mask'].to(DEVICE)
            cf  = batch['clinical_feats'].to(DEVICE)
            if not cfg['use_clinical']:
                cf = torch.zeros_like(cf)   # Zero out clinical features
            y   = batch['label'].to(DEVICE)
            with autocast():
                logits = ab_model(ids, am, cf)
                loss   = ab_crit(logits, y) / GRAD_ACCUM
            ab_amp.scale(loss).backward()
            if (step + 1) % GRAD_ACCUM == 0:
                ab_amp.unscale_(ab_opt)
                torch.nn.utils.clip_grad_norm_(ab_model.parameters(), 1.0)
                ab_amp.step(ab_opt); ab_amp.update(); ab_sched.step()
                ab_opt.zero_grad()

        # Eval
        ab_model.eval()
        val_prbs, val_lbls = [], []
        with torch.no_grad():
            for batch in ab_val_loader:
                ids = batch['input_ids'].to(DEVICE)
                am  = batch['attention_mask'].to(DEVICE)
                cf  = batch['clinical_feats'].to(DEVICE)
                if not cfg['use_clinical']:
                    cf = torch.zeros_like(cf)
                y   = batch['label'].to(DEVICE)
                with autocast():
                    logits = ab_model(ids, am, cf)
                val_prbs.extend(torch.softmax(logits, 1)[:, 1].cpu().tolist())
                val_lbls.extend(y.cpu().tolist())

        prd = [(1 if p >= 0.5 else 0) for p in val_prbs]
        vf1 = f1_score(val_lbls, prd, zero_division=0)
        if vf1 > best_ab_f1:
            best_ab_f1   = vf1
            best_ab_state = copy.deepcopy(ab_model.state_dict())
            ab_pat = 0
        else:
            ab_pat += 1
        if ab_pat >= PATIENCE:
            break

    # Final val metrics
    ab_model.load_state_dict(best_ab_state)
    ab_model.eval()
    vp2, vl2 = [], []
    with torch.no_grad():
        for batch in ab_val_loader:
            ids = batch['input_ids'].to(DEVICE)
            am  = batch['attention_mask'].to(DEVICE)
            cf  = batch['clinical_feats'].to(DEVICE)
            if not cfg['use_clinical']:
                cf = torch.zeros_like(cf)
            with autocast():
                logits = ab_model(ids, am, cf)
            vp2.extend(torch.softmax(logits, 1)[:, 1].cpu().tolist())
            vl2.extend(batch['label'].tolist())

    vp2  = np.array(vp2); vl2 = np.array(vl2)
    best_t, best_f = 0.5, 0.
    for t in np.arange(0.20, 0.81, 0.01):
        f = f1_score(vl2, (vp2 >= t).astype(int), zero_division=0)
        if f > best_f:
            best_f, best_t = f, t
    prd_f = (vp2 >= best_t).astype(int)
    result = {
        'Configuration': name,
        'F1':            round(f1_score(vl2, prd_f, zero_division=0), 4),
        'Accuracy':      round(accuracy_score(vl2, prd_f), 4),
        'AUROC':         round(roc_auc_score(vl2, vp2) if len(np.unique(vl2))>1 else 0., 4),
        'Sensitivity':   round(recall_score(vl2, prd_f, pos_label=1, zero_division=0), 4),
    }
    print(f'    → F1={result["F1"]:.4f}  Acc={result["Accuracy"]:.4f}  AUROC={result["AUROC"]:.4f}')
    torch.cuda.empty_cache()
    return result

