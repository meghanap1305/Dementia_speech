"""## §10b · Significance Testing vs. Baselines

We apply McNemar's test (for classification accuracy) and a bootstrap-based DeLong test (for AUROC) to evaluate statistical significance of improvements over published baselines.

"""

# ── McNemar's test against hypothetical baseline ──────────────────────────────
# NOTE: To properly compare, you need the per-sample predictions from
# the baseline model on the same test split. Below shows the template:
#
#   baseline_preds = np.array([...])  # load from baseline model output
#   our_preds      = final_preds
#
# As a demonstration we show the test structure:

print('=== McNemar Test Template ===')
print("""
# Compute contingency table:
#   b = cases where baseline correct, ours wrong
#   c = cases where baseline wrong, ours correct
both_correct    = ((baseline_preds == labels) & (our_preds == labels)).sum()
baseline_only   = ((baseline_preds == labels) & (our_preds != labels)).sum()  # b
ours_only       = ((baseline_preds != labels) & (our_preds == labels)).sum()  # c
both_wrong      = ((baseline_preds != labels) & (our_preds != labels)).sum()
contingency = np.array([[both_correct, baseline_only],
                         [ours_only,   both_wrong]])
result = mcnemar_test(contingency, exact=False, correction=True)
print(f'McNemar chi2={result.statistic:.4f}  p={result.pvalue:.4f}')
print('Significant (p<0.05):', result.pvalue < 0.05)
""")

# ── Bootstrap DeLong AUROC comparison ─────────────────────────────────────────
print('=== Bootstrap AUROC Comparison (DeLong-style) ===')

def bootstrap_auroc_diff(y_true, y_prob_a, y_prob_b, n_boot=10000, seed=42):
    """
    Bootstrap test: H0: AUROC_a == AUROC_b
    Returns p-value (two-sided) for the difference.
    """
    rng   = np.random.default_rng(seed)
    n     = len(y_true)
    diffs = []
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        try:
            a = roc_auc_score(y_true[idx], y_prob_a[idx])
            b = roc_auc_score(y_true[idx], y_prob_b[idx])
            diffs.append(a - b)
        except Exception:
            pass
    diffs   = np.array(diffs)
    obs_diff = roc_auc_score(y_true, y_prob_a) - roc_auc_score(y_true, y_prob_b)
    # Shift distribution to be centered at 0 (H0)
    p_value = np.mean(np.abs(diffs - diffs.mean()) >= np.abs(obs_diff))
    ci_lo   = np.percentile(diffs, 2.5)
    ci_hi   = np.percentile(diffs, 97.5)
    return obs_diff, p_value, ci_lo, ci_hi

